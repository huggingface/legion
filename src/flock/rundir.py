def hub_api(token: str):
    from huggingface_hub import HfApi

    return HfApi(token=token)


def space_url(space_id: str) -> str:
    return "https://" + re.sub(r"[^a-z0-9-]", "-", space_id.lower().replace("/", "-")) + ".hf.space"


def board_space(c: CommsSpec, swarm: str) -> str:
    return c.space or f"{c.template.split('/')[0]}/board-{swarm}"


def board_token(master: str, slug: str) -> str:
    """The admin token of board `slug` on a multi-board Space whose MSGBOARD_OPERATOR_TOKEN is
    `master`: msgboard's hfspace/multiboard.py `board_token`, copied (msgboard is not a dependency)."""
    key = master.encode()
    cred = hmac.digest(key, ("id:" + slug).encode(), "sha256")[:8].hex()
    secret = base64.urlsafe_b64encode(hmac.digest(key, ("secret:" + slug).encode(), "sha256"))
    return f"fbt_{cred}.{secret.rstrip(b'=').decode()}"


def _write_private(path: Path, text: str) -> None:
    fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    os.fchmod(fd, 0o600)  # O_CREAT's mode only applies to a new file
    with os.fdopen(fd, "w", encoding="utf-8") as f:
        f.write(text)


def _replace_keys(path: Path, values: Mapping[str, str]) -> None:
    """Set keys already set in run.env to new values (a replaced board invite)."""
    lines = path.read_text(encoding="utf-8").splitlines()
    new = [f"{m[2]}={_quote(values[m[2]])}" if (m := _LINE.match(x)) and not m[1] and m[2] in values
           else x for x in lines]
    if new != lines:
        _write_private(path, "\n".join(new) + "\n")


def provision_board(data: Any, run_dir: Path, env: Mapping[str, str],
                    rep: InitReport) -> tuple[Check, dict[str, str]]:
    """`comms.board: space`, each step skipped when done: the operator token (board.env), the
    private Space duplicated from `comms.template` with one board named after the swarm, its
    health, the channel and a multi-use agent invite. Returns (the check, the run.env values
    BOARD_URL and `comms.invite_env`)."""
    import httpx

    try:  # the comms block and swarm name as the spec reads them; url is what this makes
        raw = {k: v for k, v in data["comms"].items() if k != "url"}
        c = CommsSpec.model_validate({**substitute(raw, dict(env)), "url": "https://pending.invalid"})
        swarm, bucket = substitute([data["swarm"], data.get("bucket") or ""], dict(env))
    except Exception as e:  # noqa: BLE001 - the spec check reports the rest
        return Check("board space", False, f"comms: {' '.join(str(e).split())}"), {}
    hf = env.get("HF_TOKEN")
    if not hf:
        from huggingface_hub import get_token

        hf = get_token()
    if not hf:
        return Check("board space", False, "needs HF_TOKEN (run.env or `hf auth login`) with write "
                                           "access to the Space's namespace"), {}
    space = board_space(c, swarm)
    url = f"{space_url(space)}/boards/{swarm}"
    bf = run_dir / BOARD_ENV
    master = (read_env_file(bf) if bf.is_file() else {}).get("BOARD_OPERATOR_TOKEN")
    try:
        api = hub_api(hf)
        exists = api.repo_exists(space, repo_type="space")
        if master is None:
            if exists:
                return Check("board space", False, f"{space} exists but {bf} has no "
                             "BOARD_OPERATOR_TOKEN: restore it, or set comms.space to a new Space"), {}
            # msgboard's token format (auth.new_token): fbt_<16 hex>.<32 bytes, urlsafe b64>
            master = (f"fbt_{secrets.token_hex(8)}."
                      + base64.urlsafe_b64encode(secrets.token_bytes(32)).rstrip(b"=").decode())
            _write_private(bf, f"# {BOARD_ENV}: the board Space's operator token (admin on every "
                               f"board there). Never sourced by a job.\nBOARD_OPERATOR_TOKEN={master}\n")
            rep.created.append(f"{BOARD_ENV} BOARD_OPERATOR_TOKEN (generated)")
        if exists:
            rep.notes.append(f"Space {space} exists: changed comms.space_variables or "
                             "space_secrets are not re-applied (edit them in its settings)")
        else:
            boards = [{"id": swarm, "name": swarm, "storage_id": swarm, "require_existing": False}]
            # a duplicate inherits none of the template's variables: copy them, minus the
            # template's own board list and replica and its demo bots (they post on the board)
            variables = {k: v.value for k, v in api.get_space_variables(c.template).items()
                         if k not in TEMPLATE_VARS_DROPPED}
            variables |= {"BOARD_READ_TOKEN": "public", "MSGBOARD_BOARDS": json.dumps(boards),
                          # the board's snapshots: a rebuild or sleep would lose it otherwise
                          **({"MSGBOARD_REPLICA": bucket.rstrip("/") + "/board"} if bucket else {}),
                          **c.space_variables}
            if variables.get("MSGBOARD_REPLICA") and "HF_TOKEN" not in c.space_secrets:
                return Check("board space", False, "MSGBOARD_REPLICA needs the Space secret HF_TOKEN: "
                             "set comms.space_secrets: {HF_TOKEN: <run.env name of a token "
                             "scoped to that bucket>}"), {}
            if missing := [n for n in c.space_secrets.values() if not env.get(n)]:
                return Check("board space", False, f"comms.space_secrets: unset in {RUN_ENV}: "
                                                   f"{', '.join(missing)}"), {}
            api.duplicate_repo(
                c.template, space, repo_type="space", private=True, exist_ok=True,
                space_hardware=c.space_hardware,
                space_secrets=[{"key": "MSGBOARD_OPERATOR_TOKEN", "value": master},
                               *({"key": k, "value": env[n]} for k, n in c.space_secrets.items())],
                space_variables=[{"key": k, "value": v} for k, v in variables.items()])
            rep.created.append(f"Space {space} (private, from {c.template})")
        h = {"Authorization": f"Bearer {hf}"}  # the private Space's gate
        end = time.monotonic() + BOARD_WAIT_S
        while True:
            try:
                code: int | str = httpx.get(f"{url}/v1/health", headers=h, timeout=10).status_code
            except httpx.HTTPError as e:  # building or restarting
                code = type(e).__name__
            if code == 200:
                break
            if time.monotonic() > end:
                return Check("board space", False, f"{url}/v1/health -> {code} after "
                                                   f"{BOARD_WAIT_S:.0f} s"), {}
            _sleep(10)
        h["X-Msgboard-Token"] = board_token(master, swarm)
        r = httpx.post(f"{url}/v1/channels", json={"name": c.channel}, headers=h, timeout=30)
        if r.status_code not in (200, 201, 409):  # 409 channel_exists
            return Check("board space", False, f"create #{c.channel}: {r.status_code} {r.text[:200]}"), {}
        out = {"BOARD_URL": url}
        if (old := env.get(c.invite_env)) and (
                (r := httpx.get(f"{url}/v1/join/{old}", headers=h, timeout=30)).status_code == 404
                or r.status_code == 200 and r.json().get("status") != "active"):
            rep.notes.append(f"{RUN_ENV} {c.invite_env}: the invite no longer works; replaced")
            old = None
        if not old:
            r = httpx.post(f"{url}/v1/invites", headers=h, timeout=30, json={
                "kind": "agent", "role": "guest", "channels": [c.channel], "max_uses": None,
                "label": f"flock {swarm}"})
            if r.status_code != 201:
                return Check("board space", False, f"agent invite: {r.status_code} {r.text[:200]}"), out
            out[c.invite_env] = r.json()["code"]
    except Exception as e:  # noqa: BLE001 - any Hub or board error is the check's answer
        return Check("board space", False, f"{space}: {type(e).__name__}: {e}"), {}
    return Check("board space", True, f"{space}: board {swarm} answers, #{c.channel}, "
                                      f"{c.invite_env} set"), out


ORG_SPACE = re.compile(r"https://huggingfaceswarms-([a-z0-9-]+)\.hf\.space(?:/.*)?")


def dashboard_row(spec: SwarmSpec) -> dict[str, Any]:
    """The run's flock-overview row (the keys of its experiments.json entries). Never a token."""
    d, c = spec.dashboard, spec.comms
    assert d is not None
    board = c.url + "/" if c else None
    return {
        "id": spec.swarm, "name": d.name or spec.swarm, "title": d.title, "setup": d.setup,
        "board_id": board.split("/boards/")[1].split("/")[0] if board and "/boards/" in board else None,
        "board": board,
        "board_public": f"https://huggingface.co/spaces/{board_space(c, spec.swarm)}"
        if c and c.board == "space" else None,
        "viewer": d.viewer,
        "viewer_public": d.viewer_public or (f"https://huggingface.co/spaces/HuggingFaceSwarms/{m[1]}"
                                             if (m := ORG_SPACE.fullmatch(d.viewer)) else None),
        # the viewer reads the controller's files from <bucket>/controller/<swarm>
        "viewer_run": f"{spec.bucket.removeprefix('hf://buckets/').rstrip('/')}/{spec.swarm}",
        "dataset": d.dataset, "code_repo": d.code_repo, "spec_url": d.spec_url}


def register_dashboard(spec: SwarmSpec, env: Mapping[str, str]) -> Check:
    """Write (or rewrite) `<dashboard.registry>/runs/<swarm>.json`."""
    d = spec.dashboard
    if d is None:
        return Check("dashboard", None, "no dashboard block")
    token = env.get("HF_TOKEN")
    if not token:
        from huggingface_hub import get_token

        token = get_token()
    if not token:
        return Check("dashboard", False, f"needs HF_TOKEN to write to {d.registry}")
    rel = f"runs/{spec.swarm}.json"
    row = dashboard_row(spec)
    # the overview sends its HF token to `board` and `viewer`: only the org's Spaces
    if bad := [k for k in ("board", "viewer") if not ORG_SPACE.fullmatch(row[k] or "")]:
        return Check("dashboard", False, f"{' and '.join(bad)} must be https://huggingfaceswarms-"
                     f"*.hf.space urls (the overview drops others): {[row[k] for k in bad]}")
    if row["viewer_run"].split("/")[0] != d.registry.split("/")[3]:
        return Check("dashboard", False, f"viewer_run {row['viewer_run']} is not in the registry's "
                                         f"namespace ({d.registry})")
    try:
        with tempfile.TemporaryDirectory() as t:
            f = Path(t) / "row.json"
            f.write_text(json.dumps(row, indent=1) + "\n", encoding="utf-8")
            bucket_store(d.registry, token).upload([(f, rel)])
    except Exception as e:  # noqa: BLE001 - any Hub error is the check's answer
        return Check("dashboard", False, f"{d.registry}/{rel}: {type(e).__name__}: {e}")
    return Check("dashboard", True, f"{d.registry}/{rel} written")


# ---------------------------------------------------------------- init

def init(run_dir: str | Path, experiment: str | Path | None = None, *,
         secrets_file: str | Path | None = None, profile: str | Path | None = None,
         env: Mapping[str, str] = os.environ) -> InitReport:
    """`flock init`: create what RUN_DIR is missing (logs/, hosts/, the experiment copy, the
    cluster profile's copy cluster.env, run.env with per-run tokens; `secrets_file` fills
    run.env keys), then run every check. Raises ValueError when there is nothing to copy from."""
    from flock.ops import SpecError, check_spec, read_spec
    from flock.secrets_file import SecretsFileError, read_file

    rep = InitReport()
    d = Path(run_dir)
    for sub in ("", "logs", "hosts"):
        if not (d / sub).is_dir():
            (d / sub).mkdir(parents=True)
            rep.created.append(f"{d / sub}/")
    exp = d / EXPERIMENT
    copy_experiment(Path(experiment) if experiment else None, exp, rep)
    copy_profile(Path(profile) if profile else None, d / CLUSTER_ENV, rep)
    env_files = [str(d / f) for f in (CLUSTER_ENV, RUN_ENV) if f == RUN_ENV or (d / f).is_file()]
    spec_file = exp / "spec.yaml"
    try:
        data = load_spec_yaml(spec_file.read_text(encoding="utf-8"))
    except Exception as e:  # noqa: BLE001 - unreadable or broken YAML: the spec check says so
        rep.checks.append(Check("spec", False, f"{spec_file}: {' '.join(str(e).split())}"))
        return rep
    data = board_url_default(data if isinstance(data, dict) else {})
    fill: dict[str, str] = {}
    if secrets_file:
        try:
            fill = read_file(secrets_file)
        except SecretsFileError as e:
            rep.checks.append(Check("secrets file", False, str(e)))
    derived: dict[str, str] = {}
    m = _VAR.fullmatch(str((data.get("world") or {}).get("dir") or ""))
    if experiment and m and m[1] and m[2] and not Path(m[2]).is_absolute() \
            and (Path(experiment) / m[2]).is_dir() and not (exp / m[2]).is_dir():
        derived[m[1]] = str((Path(experiment) / m[2]).resolve())  # world.dir, relative to --from
    write_run_env(d / RUN_ENV, data, str(experiment or exp), fill, rep, derived)
    values = {k: v for f in env_files for k, v in read_env_file(f).items()}  # later wins
    space = (data.get("comms") or {}).get("board") == "space"
    if space:  # before the spec loads: it reads BOARD_URL
        board, made = provision_board(data, d, {**env, **values}, rep)
        rep.checks.append(board)
        if made:
            _replace_keys(d / RUN_ENV, made)
            write_run_env(d / RUN_ENV, data, str(experiment or exp), {}, rep, made)
            values = {k: v for f in env_files for k, v in read_env_file(f).items()}
    rep.checks.append(check_tokens(data, read_env_file(d / RUN_ENV)))
    try:
        spec = read_spec(str(spec_file), env_files)
        _, warnings = check_spec(spec, str(spec_file))
    except SpecError as e:
        rep.checks += [Check("spec", False, f"{spec_file} does not load with {RUN_ENV}",
                             [*e.done.get("warnings", []), *e.lines]),
                       *(Check(n, None, "skipped: needs the spec") for n in
                         ("worker slots", "bucket", "providers", "board", "world", "dashboard")),
                       check_venv({**env, **values})]
        return rep
    unset = [n for n, (default, why) in spec_keys(data).items()  # `NAME=` substitutes ""
             if default is None and not why.startswith("secret:") and not values.get(n)
             and not env.get(n)]
    rep.checks.append(Check("spec", not unset, f"{spec.swarm}: loads and validates with "
                            f"{RUN_ENV}" if not unset else f"empty, no default: {', '.join(unset)}",
                            warnings))
    secret_env = {**env, **values}
    rep.checks += [check_slots(spec), check_bucket(spec, secret_env, rep),
                   check_providers(spec, secret_env), check_board(spec, secret_env),
                   check_venv(secret_env), check_world(spec, secret_env, d),
                   register_dashboard(spec, secret_env)]
    if spec.compute.kind == "slurm":
        rep.checks += [check_capacity(spec, secret_env), check_mounts(secret_env)]
    return rep
