"""A run directory (docs/slurm.md "Deploying"): what `flock init RUN_DIR --from FOLDER` creates
and checks before `flock launch`, and how `flock --run RUN_DIR` (or FLOCK_RUN_DIR) finds the
run's env file and controller. Nothing here prints; secret values never appear in a report.

    RUN_DIR/experiment/   a copy of the experiment folder (links followed): what is launched
    RUN_DIR/run.env       mode 600: every ${VAR} the spec reads, the secrets it names, per-run tokens
    RUN_DIR/logs/, hosts/ the jobs' logs and host files (hosts/controller.host, world.host)

`init` creates only what is missing and never overwrites a run.env key or an edited copy: it
reports the difference. Running it again is the doctor. None of its checks needs a controller.
"""

from __future__ import annotations

import asyncio
import os
import re
import secrets
import shutil
import subprocess
import sys
import tempfile
from collections.abc import Mapping
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

from flock.models import SwarmSpec, load_spec_yaml, max_workers
from flock.specrender import _RUNTIME, _VAR, read_env_file

RUN_ENV = "run.env"
EXPERIMENT = "experiment"
TOKENS = ("FLOCK_TOKEN", "FLOCK_WORLD_TOKEN")  # per-run, generated by init
CTL_PORT = 7860  # what controller.sbatch binds; a host file with host:port wins
PROBE = ".flock-init-check"  # the bucket write probe, deleted again


@dataclass
class Check:
    name: str
    ok: bool | None  # None: skipped (the detail says why)
    detail: str = ""
    lines: list[str] = field(default_factory=list)


@dataclass
class InitReport:
    created: list[str] = field(default_factory=list)  # paths, run.env keys
    notes: list[str] = field(default_factory=list)  # kept differences, things to know
    checks: list[Check] = field(default_factory=list)

    @property
    def failed(self) -> bool:
        return any(c.ok is False for c in self.checks)


def run_context(run_dir: str | Path) -> tuple[dict[str, str], list[str]]:
    """(environment, env files) for commands run against RUN_DIR: FLOCK_URL from
    hosts/controller.host (else FLOCK_CURRENT for a local run's .flock/current there),
    FLOCK_TOKEN from run.env, and run.env as the first --env file."""
    d = Path(run_dir)
    env: dict[str, str] = {}
    host = d / "hosts" / "controller.host"
    h = host.read_text(encoding="utf-8").strip() if host.is_file() else ""
    if h:
        env["FLOCK_URL"] = f"http://{h}" if ":" in h else f"http://{h}:{CTL_PORT}"
    elif (d / ".flock" / "current").is_file():
        env["FLOCK_CURRENT"] = str(d / ".flock" / "current")
    if not (d / RUN_ENV).is_file():
        return env, []
    if tok := read_env_file(d / RUN_ENV).get("FLOCK_TOKEN"):
        env["FLOCK_TOKEN"] = tok
    return env, [str(d / RUN_ENV)]


# ---------------------------------------------------------------- what the spec reads

def spec_keys(data: Any) -> dict[str, tuple[str | None, str]]:
    """Name -> (default or None, one-line comment) for every ${VAR} in the raw spec's values
    (comments in the file are not values), then every secret it names, in spec order."""
    out: dict[str, tuple[str | None, str]] = {}
    paths: dict[str, list[str]] = {}

    def walk(v: Any, path: str) -> None:
        if isinstance(v, str):
            for m in _VAR.finditer(v):
                name, default = m.groups()
                if name and name not in _RUNTIME:
                    paths.setdefault(name, []).append(path)
                    if out.get(name, (None,))[0] is None:
                        out[name] = (default, "")
        elif isinstance(v, dict):
            for k, x in v.items():
                walk(x, f"{path}.{k}" if path else str(k))
        elif isinstance(v, list):
            for x in v:
                walk(x, path)

    walk(data, "")
    for name, (default, _) in out.items():
        where = paths[name][0] + (f" (+{len(paths[name]) - 1} more)" if len(paths[name]) > 1 else "")
        out[name] = (default, f"{where} (default: {default})" if default is not None
                     else f"{where} (required: no default)")
    named = [("HF_TOKEN", "bucket sync and the Hub")]
    named += [(p.get("api_key_env"), f"providers.{n}.api_key_env")
              for n, p in (data.get("providers") or {}).items() if isinstance(p, dict)]
    named.append(((data.get("comms") or {}).get("invite_env"), "comms.invite_env"))
    named += [(s, f"types.{n}.secrets") for n, t in (data.get("types") or {}).items()
              if isinstance(t, dict) for s in t.get("secrets") or []]
    for name, where in named:
        if isinstance(name, str) and "${" not in name and name not in out and name not in TOKENS:
            out[name] = (None, f"secret: {where}")
    return out


def token_names(data: Any) -> list[str]:
    """The per-run tokens: FLOCK_TOKEN, plus FLOCK_WORLD_TOKEN and the spec's world.token_env
    (same value) when the world takes a token."""
    te = (data.get("world") or {}).get("token_env")
    return ["FLOCK_TOKEN", *(["FLOCK_WORLD_TOKEN"] if te else []),
            *([te] if te and te not in TOKENS else [])]


# ---------------------------------------------------------------- run.env

_LINE = re.compile(r"^\s*(#\s*)?(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)=")


def _quote(v: str) -> str:
    # shortcut: a value with a single quote is written as is; sourcing it in sh may break
    return v if re.fullmatch(r"[\w./:@,+=%-]*", v) or "'" in v else f"'{v}'"


def write_run_env(path: Path, data: Any, folder: str, fill: Mapping[str, str],
                  rep: InitReport, derived: Mapping[str, str] | None = None) -> None:
    """Create or complete run.env (mode 600): a missing key is appended, commented out when it
    has no value (the spec's default then applies); `fill` (the --secrets file) sets keys that
    are missing or commented out. A set key is never changed: a different `fill` value is
    reported by name only. `derived`: values init works out (an absolute WORLD_DIR), written
    like `fill`."""
    derived = derived or {}
    lines = path.read_text(encoding="utf-8").splitlines() if path.exists() else []
    if path.exists() and path.stat().st_mode & 0o077:
        path.chmod(0o600)
        rep.notes.append(f"{path}: mode set to 600")
    set_keys, commented = {}, {}
    for i, line in enumerate(lines):
        if m := _LINE.match(line):
            (commented if m[1] else set_keys).setdefault(m[2], i)
    current = read_env_file(path) if path.exists() else {}
    keys = spec_keys(data)
    tokens = token_names(data)
    world_tok = next((current[n] for n in tokens[1:] if current.get(n)), secrets.token_urlsafe(32))
    new: list[str] = []
    filled = False
    if not lines:
        new += [f"# {RUN_ENV} for {folder}: written by `flock init`,",
                "# mode 600. A commented key is unset: the spec's default applies. Later keys win.",
                ""]
    for name in tokens:
        if name in set_keys:
            continue
        value = world_tok if name != "FLOCK_TOKEN" else secrets.token_urlsafe(32)
        what = ("the controller API token (X-Flock-Token)" if name == "FLOCK_TOKEN"
                else "the world token (X-World-Token)" if name == "FLOCK_WORLD_TOKEN"
                else "world.token_env: the same value as FLOCK_WORLD_TOKEN")
        new += [f"# per-run token, generated: {what}", f"{name}={value}"]
        rep.created.append(f"{RUN_ENV} {name} (generated)")
    for name in [n for n in fill if n in tokens]:
        rep.notes.append(f"--secrets {name}: ignored, the run keeps its per-run token")
    for name, (default, comment) in keys.items():
        value = fill.get(name, derived.get(name))
        how = "from --secrets" if name in fill else "absolute: the copy cannot reach the default"
        if name in set_keys:
            if name in fill and value != current.get(name):
                rep.notes.append(f"{RUN_ENV} {name}: kept, differs from the --secrets file")
            continue
        if value is not None and name in commented:  # fill the placeholder in place
            lines[commented[name]] = f"{name}={_quote(value)}"
            filled = True
            rep.created.append(f"{RUN_ENV} {name} ({how})")
        elif value is not None:
            new += [f"# {comment}", f"{name}={_quote(value)}"]
            rep.created.append(f"{RUN_ENV} {name} ({how})")
        elif name not in commented:
            new += [f"# {comment}", f"#{name}={default or ''}"]
            rep.created.append(f"{RUN_ENV} {name}")
    unused = sorted(set(fill) - set(keys) - set(tokens))
    if unused:
        rep.notes.append(f"--secrets: not read by the spec, not written: {', '.join(unused)}")
    if not new and not filled:
        return
    text = "\n".join(lines + new) + "\n"
    fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    os.fchmod(fd, 0o600)  # O_CREAT's mode only applies to a new file
    with os.fdopen(fd, "w", encoding="utf-8") as f:
        f.write(text)


# ---------------------------------------------------------------- the experiment copy

def _files(root: Path) -> dict[str, Path]:
    return {str(p.relative_to(root)): p for p in sorted(root.rglob("*"))
            if p.is_file() and "__pycache__" not in p.parts}


def copy_experiment(src: Path | None, dst: Path, rep: InitReport) -> None:
    """Copy the experiment folder (links followed) into an absent or empty `dst`; else report
    how the copy differs from `src`, and change nothing."""
    if dst.is_dir() and any(dst.iterdir()):
        if src is None:
            return
        a, b = _files(src), _files(dst)
        diff = ([f"edited {r}" for r in sorted(a.keys() & b.keys())
                 if a[r].read_bytes() != b[r].read_bytes()]
                + [f"missing {r}" for r in sorted(a.keys() - b.keys())]
                + [f"added {r}" for r in sorted(b.keys() - a.keys())])
        if diff:
            rep.notes.append(f"{dst} differs from {src} (kept): " + ", ".join(diff))
        return
    if src is None:
        raise ValueError(f"{dst} is missing or empty: pass --from EXPERIMENT_FOLDER")
    if not (src / "spec.yaml").is_file():
        raise ValueError(f"{src}: no spec.yaml (an experiment folder holds spec.yaml + prompts/)")
    shutil.copytree(src, dst, symlinks=False, dirs_exist_ok=True,
                    ignore=shutil.ignore_patterns("__pycache__"))
    rep.created.append(f"{dst} (copy of {src})")


# ---------------------------------------------------------------- checks

def planned_agents(spec: SwarmSpec) -> dict[str, int]:
    """Most agents each type can have: replicas or its ramp's max, plus what its spawners may
    start (each spawner's planned count x its per-type cap), capped by limits.alive."""
    want = {n: max(ts.replicas, ts.replicas_ramp.max if ts.replicas_ramp else 0)
            for n, ts in spec.types.items()}
    for parent, rule in spec.spawn.items():  # shortcut: one pass, so spawn chains deeper than 1 undercount
        for t in rule.allowed:
            cap = rule.cap_for(t) if rule.cap_for(t) is not None else rule.max
            if cap is not None and t in want:
                want[t] += want.get(parent, 0) * cap
    alive = spec.limits.alive
    return {n: min(v, alive) if alive is not None else v for n, v in want.items()}


def check_slots(spec: SwarmSpec) -> Check:
    bad, lines = False, []
    for n, want in planned_agents(spec).items():
        ts = spec.types[n]
        room = max_workers(ts) * max(1, ts.agents_per_worker)
        bad |= want > room
        lines.append(f"{'OVER: ' if want > room else ''}type {n}: {want} agents planned, "
                     f"{max_workers(ts)} workers x {ts.agents_per_worker} = {room} slots")
    return Check("worker slots", not bad, "planned agents fit" if not bad else
                 "planned agents exceed the worker slots", lines)


def bucket_store(url: str, token: str):
    from flock.worker.sync import HubBucketStore

    return HubBucketStore(url, token=token)


def check_bucket(spec: SwarmSpec, env: Mapping[str, str], rep: InitReport) -> Check:
    if not spec.bucket:
        return Check("bucket", None, "not set (compute local keeps agents in the run dir)")
    token = env.get("HF_TOKEN")
    if not token:
        from huggingface_hub import get_token

        token = get_token()
    if not token:
        return Check("bucket", None, f"skipped: no HF token to check {spec.bucket} (set HF_TOKEN "
                                     "in run.env or `hf auth login`)")
    try:
        b = bucket_store(spec.bucket, token)
        with tempfile.NamedTemporaryFile() as f:
            b.upload([(Path(f.name), PROBE)])
        b.delete([PROBE])
        found = b.first(f"{spec.swarm}/")
    except Exception as e:  # noqa: BLE001 - any Hub error is the check's answer
        return Check("bucket", False, f"{spec.bucket}: not writable: {type(e).__name__}: {e}")
    if found:
        rep.notes.append(f"bucket {spec.bucket} already holds data for swarm {spec.swarm} "
                         f"({found}): `flock launch` refuses a fresh start (--adopt takes it over)")
    return Check("bucket", True, f"{spec.bucket} writable")


def check_tokens(data: Any, values: Mapping[str, str]) -> Check:
    names = token_names(data)
    unset = [n for n in names if not values.get(n)]
    if unset:
        return Check("tokens", False, f"unset in {RUN_ENV}: {', '.join(unset)}")
    world = [n for n in names if n != "FLOCK_TOKEN"]
    if len({values[n] for n in world}) > 1:
        return Check("tokens", False, f"{' and '.join(world)} differ in {RUN_ENV} "
                                      "(the spec's world.token_env must equal FLOCK_WORLD_TOKEN)")
    return Check("tokens", True, f"{', '.join(names)} set in {RUN_ENV}")


def check_providers(spec: SwarmSpec, env: Mapping[str, str]) -> Check:
    import httpx

    from flock.controller.preflight import run_preflight
    from flock.ops import provider_backed

    if not provider_backed(spec):
        return Check("providers", None, "no provider-backed models")

    async def go():
        async with httpx.AsyncClient() as client:
            return await run_preflight(spec, env, client)

    rep = asyncio.run(go())
    lines = [f"{r.model}: " + ("unverified" if r.unverified else "ok" if r.ok else "FAIL")
             + (f" {r.latency_ms} ms" if r.latency_ms is not None else "")
             + (f" ({r.error})" if r.error else "") for r in rep.results]
    unv = sum(r.unverified for r in rep.results)
    bad = sum(not r.ok and not r.unverified for r in rep.results)
    return Check("providers", rep.ok, f"{len(rep.results) - unv - bad} answered a tool call, "
                 f"{unv} unverified (no key), {bad} failed", lines)


def check_board(spec: SwarmSpec, env: Mapping[str, str]) -> Check:
    """The invite is set and the board answers. No join: it may use up a limited invite or
    rotate the host token a running controller holds."""
    import httpx

    c = spec.comms
    if c is None:
        return Check("board", None, "no comms block")
    if not env.get(c.invite_env):
        return Check("board", False, f"comms.invite_env: {c.invite_env} is not set in {RUN_ENV}")
    url = c.url.rstrip("/") + "/v1/health"
    try:
        code = httpx.get(url, timeout=10).status_code
    except httpx.HTTPError as e:
        return Check("board", False, f"{url}: {type(e).__name__}: {e}")
    return Check("board", code == 200, f"{c.invite_env} set; {url} -> {code}; join not tested")


def check_venv(env: Mapping[str, str]) -> Check:
    venv = env.get("WORKER_VENV") or env.get("VENV")  # the Slurm scripts' names (common.sh)
    py = f"{venv}/bin/python" if venv else sys.executable
    try:
        r = subprocess.run([py, "-I", "-c", "import flock.worker"], capture_output=True,
                           text=True, timeout=120, check=False)
    except (OSError, subprocess.SubprocessError) as e:
        return Check("venv", False, f"{py}: {type(e).__name__}: {e}")
    if r.returncode:
        tail = (r.stderr.strip().splitlines() or ["?"])[-1]
        return Check("venv", False, f"{py} cannot import flock.worker: {tail}")
    return Check("venv", True, f"{py} imports flock.worker")


def check_world(spec: SwarmSpec, env: Mapping[str, str], run_dir: Path) -> Check:
    import httpx

    from flock.world.doctor import doctor
    from flock.world.protocol import WORLD_HOST_VAR

    w = spec.world
    if w is None or not w.url:
        return Check("world", None, "no world.url")
    url = w.url
    if WORLD_HOST_VAR in url:
        hf = run_dir / "hosts" / "world.host"
        host = hf.read_text(encoding="utf-8").strip() if hf.is_file() else ""
        if not host:
            return Check("world", None, f"skipped: the world is not up (no {hf})")
        url = url.replace(WORLD_HOST_VAR, host)
    try:
        httpx.get(url.rstrip("/") + "/healthz", timeout=5)
    except httpx.HTTPError:
        return Check("world", None, f"skipped: the world is not up ({url} does not answer)")
    lines, failed = doctor(url, env.get(w.token_env or "FLOCK_WORLD_TOKEN"))
    return Check("world", not failed, f"{url} conformance", lines)


# ---------------------------------------------------------------- init

def init(run_dir: str | Path, experiment: str | Path | None = None, *,
         secrets_file: str | Path | None = None,
         env: Mapping[str, str] = os.environ) -> InitReport:
    """`flock init`: create what RUN_DIR is missing (logs/, hosts/, the experiment copy,
    run.env with per-run tokens; `secrets_file` fills run.env keys), then run every check.
    Raises ValueError when there is nothing to copy from."""
    from flock.ops import SpecError, check_spec, read_spec
    from flock.secrets_file import SecretsFileError, read_file

    rep = InitReport()
    d = Path(run_dir)
    for sub in ("", "logs", "hosts"):
        if not (d / sub).is_dir():
            (d / sub).mkdir(parents=True)
            rep.created.append(f"{d / sub}/")
    exp = d / EXPERIMENT
    copy_experiment(Path(experiment) if experiment else None, exp, rep)
    spec_file = exp / "spec.yaml"
    try:
        data = load_spec_yaml(spec_file.read_text(encoding="utf-8"))
    except Exception as e:  # noqa: BLE001 - unreadable or broken YAML: the spec check says so
        rep.checks.append(Check("spec", False, f"{spec_file}: {' '.join(str(e).split())}"))
        return rep
    data = data if isinstance(data, dict) else {}
    fill: dict[str, str] = {}
    if secrets_file:
        try:
            fill = read_file(secrets_file)
        except SecretsFileError as e:
            rep.checks.append(Check("secrets file", False, str(e)))
    derived: dict[str, str] = {}
    m = _VAR.fullmatch(str((data.get("world") or {}).get("dir") or ""))
    if experiment and m and m[1] and m[2] and not Path(m[2]).is_absolute() \
            and (Path(experiment) / m[2]).is_dir() and not (exp / m[2]).is_dir():
        derived[m[1]] = str((Path(experiment) / m[2]).resolve())  # world.dir, relative to --from
    write_run_env(d / RUN_ENV, data, str(experiment or exp), fill, rep, derived)
    values = read_env_file(d / RUN_ENV)
    rep.checks.append(check_tokens(data, values))
    try:
        spec = read_spec(str(spec_file), [str(d / RUN_ENV)])
        _, warnings = check_spec(spec, str(spec_file))
    except SpecError as e:
        rep.checks += [Check("spec", False, f"{spec_file} does not load with {RUN_ENV}",
                             [*e.done.get("warnings", []), *e.lines]),
                       *(Check(n, None, "skipped: needs the spec") for n in
                         ("worker slots", "bucket", "providers", "board", "world")),
                       check_venv({**env, **values})]
        return rep
    unset = [n for n, (default, why) in spec_keys(data).items()  # `NAME=` substitutes ""
             if default is None and not why.startswith("secret:") and not values.get(n)
             and not env.get(n)]
    rep.checks.append(Check("spec", not unset, f"{spec.swarm}: loads and validates with "
                            f"{RUN_ENV}" if not unset else f"empty, no default: {', '.join(unset)}",
                            warnings))
    secret_env = {**env, **values}
    rep.checks += [check_slots(spec), check_bucket(spec, secret_env, rep),
                   check_providers(spec, secret_env), check_board(spec, secret_env),
                   check_venv(secret_env), check_world(spec, secret_env, d)]
    return rep
