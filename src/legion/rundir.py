def _bash_values(sf: Path, env: Mapping[str, str]) -> dict[str, str]:
    """The secrets file's assigned names, valued as common.sh's `set -a; . file` leaves them."""
    out = subprocess.run(["bash", "-c", 'set -a; . "$1"; set +a; env -0', "legion-init", str(sf)],
                         capture_output=True, timeout=30, env=dict(env), check=False)
    if out.returncode:
        # no stderr: bash echoes the offending line, which can be a secret
        raise RuntimeError(f"{sf}: sourcing it with bash exited {out.returncode}")
    got = dict(kv.split("=", 1) for kv in out.stdout.decode(errors="replace").split("\0") if "=" in kv)
    # names read leniently: the jobs source any bash (umask, if blocks), init only needs what is assigned
    names = re.findall(r"^\s*(?:export\s+)?([A-Za-z_]\w*)=", sf.read_text(errors="replace"), re.MULTILINE)
    return {k: got[k] for k in names if k in got}


def init(run_dir: str | Path, experiment: str | Path | None = None, *,
         secrets_file: str | Path | None = None, profile: str | Path | None = None,
         env: Mapping[str, str] = os.environ) -> InitReport:
    """`legion init`: create what RUN_DIR is missing (logs/, hosts/, the experiment copy, the
    cluster profile's copy cluster.env, run.env with per-run tokens; `secrets_file` fills
    run.env keys), then run every check. Raises ValueError when there is nothing to copy from."""
    from legion.ops import SpecError, check_spec, read_spec
    from legion.secrets_file import SecretsFileError, read_file

    rep = InitReport()
    d = Path(run_dir)
    for sub in ("", "logs", "hosts"):
        if not (d / sub).is_dir():
            (d / sub).mkdir(parents=True)
            rep.created.append(f"{d / sub}/")
    exp = d / EXPERIMENT
    copy_experiment(Path(experiment) if experiment else None, exp, rep)
    copy_profile(Path(profile) if profile else None, d / CLUSTER_ENV, rep)
    env_files = [str(d / f) for f in (CLUSTER_ENV, RUN_ENV) if f == RUN_ENV or (d / f).is_file()]
    spec_file = exp / "spec.yaml"
    try:
        data = load_spec_yaml(spec_file.read_text(encoding="utf-8"))
    except Exception as e:  # noqa: BLE001 - unreadable or broken YAML: the spec check says so
        rep.checks.append(Check("spec", False, f"{spec_file}: {' '.join(str(e).split())}"))
        return rep
    data = board_url_default(data if isinstance(data, dict) else {})
    fill: dict[str, str] = {}
    if secrets_file:
        try:
            fill = read_file(secrets_file)
        except SecretsFileError as e:
            rep.checks.append(Check("secrets file", False, str(e)))
    derived: dict[str, str] = {}
    m = _VAR.fullmatch(str((data.get("world") or {}).get("dir") or ""))
    if experiment and m and m[1] and m[2] and not Path(m[2]).is_absolute() \
            and (Path(experiment) / m[2]).is_dir() and not (exp / m[2]).is_dir():
        derived[m[1]] = str((Path(experiment) / m[2]).resolve())  # world.dir, relative to --from
    write_run_env(d / RUN_ENV, data, str(experiment or exp), fill, rep, derived,
                  read_env_file(d / CLUSTER_ENV) if (d / CLUSTER_ENV).is_file() else None)
    cluster = read_env_file(d / CLUSTER_ENV) if (d / CLUSTER_ENV).is_file() else {}
    jobs_secrets: dict[str, str] = {}  # the profile's SECRETS_FILE, as common.sh's source_env_600
    if sf := cluster.get("SECRETS_FILE") or env.get("SECRETS_FILE"):
        sf = Path(Template(str(sf)).safe_substitute({**env, **cluster})).expanduser()
        st = sf.stat() if sf.is_file() else None
        if st is None:
            rep.checks.append(Check("secrets file", False, f"{sf}: no such file"))
        elif st.st_uid != os.getuid() or stat.S_IMODE(st.st_mode) not in (0o600, 0o400):
            rep.checks.append(Check("secrets file", False, f"{sf}: must be yours and mode 600 "
                                    f"(chmod 600 '{sf}'); the jobs refuse it"))
        else:
            try:
                jobs_secrets = _bash_values(sf, {**env, **cluster})
            except (RuntimeError, subprocess.TimeoutExpired, OSError) as e:
                rep.checks.append(Check("secrets file", False, str(e) if isinstance(e, RuntimeError)
                                        else f"{sf}: sourcing it with bash failed ({type(e).__name__})"))
    values = {**cluster, **jobs_secrets, **read_env_file(d / RUN_ENV)}  # the jobs' order
    space = (data.get("comms") or {}).get("board") == "space"
    if space:  # before the spec loads: it reads BOARD_URL
        board, made = provision_board(data, d, {**env, **values}, rep)
        rep.checks.append(board)
        if made:
            _replace_keys(d / RUN_ENV, made)
            write_run_env(d / RUN_ENV, data, str(experiment or exp), {}, rep, made)
            values = {**cluster, **jobs_secrets, **read_env_file(d / RUN_ENV)}
    rep.checks.append(check_tokens(data, read_env_file(d / RUN_ENV)))
    try:
        spec = read_spec(str(spec_file), env_files)
        _, warnings = check_spec(spec, str(spec_file))
    except SpecError as e:
        rep.checks += [Check("spec", False, f"{spec_file} does not load with {RUN_ENV}",
                             [*e.done.get("warnings", []), *e.lines]),
                       *(Check(n, None, "skipped: needs the spec") for n in
                         ("worker slots", "bucket", "providers", "board", "world", "dashboard")),
                       check_venv({**env, **values})]
        return rep
    # secrets known once compiled (a Harbor resource's default token_env): their lines too
    more = {s for ts in spec.types.values() for s in ts.secrets} - set(spec_keys(data))
    if more:
        compiled = {n: {"secrets": [s for s in ts.secrets if s in more]}
                    for n, ts in spec.types.items()}
        write_run_env(d / RUN_ENV, {"types": compiled}, str(experiment or exp),
                      {k: v for k, v in fill.items() if k in more}, rep)
    unset = [n for n, (default, why) in spec_keys(data).items()  # `NAME=` substitutes ""
             if default is None and not why.startswith("secret:") and not values.get(n)
             and not env.get(n)]
    rep.checks.append(Check("spec", not unset, f"{spec.swarm}: loads and validates with "
                            f"{RUN_ENV}" if not unset else f"empty, no default: {', '.join(unset)}",
                            warnings))
    secret_env = {**env, **values}
    rep.checks += [check_slots(spec), check_task(spec), check_bucket(spec, secret_env, rep),
                   check_providers(spec, secret_env), check_board(spec, secret_env),
                   check_venv(secret_env), check_world(spec, secret_env, d),
                   register_dashboard(spec, secret_env)]
    if spec.compute.kind == "slurm":  # the job scripts `legion launch` submits; an edited copy is kept
        copy_experiment(SLURM_SCRIPTS, d / "slurm", rep, need=None)
        rep.checks += [check_capacity(spec, secret_env), check_mounts(secret_env)]
        if spec.world and spec.world.command and (unset := [n for n in ("WORLD_CPUS", "WORLD_MEM")
                                                            if not values.get(n)]):
            rep.notes.append(f"{', '.join(unset)} unset: the world job gets world.sbatch's small "
                             f"default; set them in {CLUSTER_ENV} or {RUN_ENV}")
        if (d / CLUSTER_ENV).is_file():
            rep.checks.append(check_cluster_env(d / CLUSTER_ENV))
    return rep
