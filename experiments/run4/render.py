"""Render a run-4 spec without starting services or contacting any API: flock's own
substitution and overlay (`flock apply spec.yaml --env run.env --overlay spec.slurm.yaml`)
plus the two things a spec file cannot say: OPENAI_BASE_URLS as a list and the smoke variant."""
from __future__ import annotations

import argparse
import os
from pathlib import Path

import yaml

from flock.models import SwarmSpec
from flock.specrender import render as render_spec

HERE = Path(__file__).resolve().parent


def render(variant="jobs", compute=None, env_files=()):
    kind = compute or ("slurm" if variant == "jobs" else "local")
    data = render_spec(HERE / "spec.yaml", env_files,
                       [HERE / "spec.slurm.yaml"] if kind != "local" else [])
    if kind == "external":
        data["compute"] = kind
    if urls := [u.strip() for u in os.environ.get("OPENAI_BASE_URLS", "").split(",") if u.strip()]:
        data["providers"]["vllm"].update(base_url=urls[0], base_urls=urls)
    if variant == "smoke":
        for t in data["types"].values():  # agent, agent-spawner, agent-child
            t["loop"]["while"] = {"until": "30m", "max_rounds": 100}
    SwarmSpec.model_validate(data)
    return data


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--variant", choices=["jobs", "smoke", "selfhosted"], default="jobs")
    parser.add_argument("--compute", choices=["slurm", "local", "external"])
    parser.add_argument("--env", action="append", default=[], help="NAME=value file (repeatable)")
    parser.add_argument("--out", type=Path)
    args = parser.parse_args()
    out = args.out or HERE / "spec.slurm.local.yaml"
    out.write_text("# Generated by render.py; edit spec.yaml / spec.slurm.yaml and render again.\n" +
                   yaml.safe_dump(render(args.variant, args.compute, args.env), sort_keys=False))
    print(out)


if __name__ == "__main__":
    main()
