"""Render a run-4 spec without starting services or contacting any API."""

import argparse
import json
import os
from pathlib import Path

import yaml

from flock.models import SwarmSpec, load_spec_yaml

HERE = Path(__file__).resolve().parent


def render(variant="jobs", placeholders=False, compute=None):
    def env(name, default):
        return default if placeholders else os.environ.get(name, default)
    # The JSON round trip expands spec.yaml's `<<: *agent` clones into plain, unshared maps,
    # so the output has no YAML aliases and an edit to one type never reaches another.
    data = json.loads(json.dumps(load_spec_yaml((HERE / "spec.yaml").read_text())))
    provider = data["providers"]["vllm"]
    urls = [u.strip() for u in env("OPENAI_BASE_URLS", "").split(",") if u.strip()]
    provider["base_url"] = urls[0] if urls else env("OPENAI_BASE_URL", provider["base_url"])
    if urls:
        provider["base_urls"] = urls
    data["models"]["worker-pi"]["model"] = "vllm:" + env("MODEL_WORKER", "MODEL_WORKER")
    data["comms"].update(url=env("CHATBOT_BOARD_URL", data["comms"]["url"]),
                         channel=env("CHATBOT_CHANNEL", "general"))
    if run := env("CHATBOT_RUN", ""):
        data["swarm"] = run
    kind = compute or ("slurm" if variant == "jobs" else "local")
    if kind != "local":
        # Keep RUN3 aliases for the liaison's existing sourced environment files.
        data["bucket"] = env("RUN4_BUCKET", env("RUN3_BUCKET", "hf://buckets/cmpatino/eliza-swarm"))
        data["namespace"] = env("RUN4_NAMESPACE", env("RUN3_NAMESPACE", "cmpatino"))
        data["world"] = {"url": env("RUN4_WORLD_URL", env("RUN3_WORLD_URL", "http://${WORLD_HOST}:7860")),
                         "token_env": "CHATBOT_WORLD_TOKEN"}
        data["compute"] = {"kind": "slurm", "partition": env("RUN3_SLURM_PARTITION", "hopper-cpu"),
                           "cpus": 4, "mem": "7G", "time": "54:00:00"} if kind == "slurm" else kind
    if variant == "smoke":
        for t in data["types"].values():  # agent, agent-spawner, agent-child
            t["loop"]["while"] = {"until": "30m", "max_rounds": 100}
    SwarmSpec.model_validate(data)
    return data


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--variant", choices=["jobs", "smoke", "selfhosted"], default="jobs")
    parser.add_argument("--compute", choices=["slurm", "local", "external"])
    parser.add_argument("--committed", action="store_true")
    parser.add_argument("--out", type=Path)
    args = parser.parse_args()
    out = args.out or HERE / ("spec.slurm.local.yaml" if not args.committed else "spec.slurm.yaml")
    out.write_text("# Generated by render.py; edit spec.yaml and render again.\n" +
                   yaml.safe_dump(render(args.variant, args.committed, args.compute), sort_keys=False))
    print(out)


if __name__ == "__main__":
    main()
