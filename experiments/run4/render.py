"""Write a run-4 spec file (for waves.py and the controller job) without contacting any API.
A thin wrapper over what `flock apply|update spec.yaml --env run.env --overlay spec.slurm.yaml
[--overlay spec.smoke.yaml]` reads: the variant picks the overlays."""
from __future__ import annotations

import argparse
from pathlib import Path

import yaml

from flock.models import SwarmSpec
from flock.specrender import render as render_spec

HERE = Path(__file__).resolve().parent


def render(variant="jobs", compute=None, env_files=()):
    kind = compute or ("slurm" if variant == "jobs" else "local")
    overlays = ([HERE / "spec.slurm.yaml"] if kind != "local" else []) + (
        [HERE / "spec.smoke.yaml"] if variant == "smoke" else [])
    data = render_spec(HERE / "spec.yaml", env_files, overlays)
    if kind == "external":
        data["compute"] = kind
    SwarmSpec.model_validate(data)
    return data


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--variant", choices=["jobs", "smoke", "selfhosted"], default="jobs")
    parser.add_argument("--compute", choices=["slurm", "local", "external"])
    parser.add_argument("--env", action="append", default=[], help="NAME=value file (repeatable)")
    parser.add_argument("--out", type=Path)
    args = parser.parse_args()
    out = args.out or HERE / "spec.slurm.local.yaml"
    out.write_text("# Generated by render.py; edit spec.yaml and its overlays instead.\n" +
                   yaml.safe_dump(render(args.variant, args.compute, args.env), sort_keys=False))
    print(out)


if __name__ == "__main__":
    main()
