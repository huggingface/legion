"""Render run 3's spec from spec.yaml and the environment.

    python experiments/run3/render.py [--variant selfhosted|smoke|standin|jobs|router-smoke] [--out FILE]

Variants (one source, spec.yaml):
- selfhosted (default): compute local, the operator's vLLM endpoint, price 0, no $ caps. The
  single-job path (the bootstrap), for up to ~50 agents.
- jobs: compute hf-jobs, the world served from a Space (world.url), agents_per_worker 25,
  worker slots computed from the cap in waves.yaml. For 50 to 1,000 agents.
- smoke: selfhosted for the 30-min endpoint smoke: the loop ends at 30 min (`while.until`)
  with `max_rounds` 120 per agent; prices 0, no $ caps (waves-smoke.yaml: 20/20/20, cap 40).
- standin: the smoke against the HF router as a stand-in endpoint (OPENAI_BASE_URL defaults to
  the router, the key is HF_TOKEN, MODEL_WORKER defaults to the router's DeepSeek id, which the
  interviewers use too), router prices, `every: 60s`, a 20-min loop, $3.00 per agent, $0.33
  per prompt, $0.15 per interviewer, $30 hard stop (waves-standin.yaml: 10 + 10, cap 20).
- router-smoke: the HF router with DeepSeek at router prices and $ caps, for a short smoke
  without the endpoint (until 20m, $2.50 per agent, $15 in total).

Environment (unset: the placeholder stays, so the spec loads but preflight fails):
  OPENAI_BASE_URL     the vLLM server, ending in /v1
  OPENAI_API_KEY      optional (named in the spec, never written; any value without --api-key)
  MODEL_WORKER        the served model id; MODEL_INTERVIEWER defaults to it
  CHATBOT_BOARD_URL, CHATBOT_CHANNEL, CHATBOT_RUN (swarm run3-<run>)
  jobs: RUN3_NAMESPACE, RUN3_BUCKET (hf://buckets/<ns>/<bucket>), RUN3_WORLD_URL (the Space)
--out default: <variant spec>.local.yaml next to spec.yaml (spec.local.yaml, ...). Without
--out and with --committed, writes spec.<variant>.yaml (placeholders only)."""

from __future__ import annotations

import argparse
import math
import os
import sys
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

from waves import load

from flock.models import load_spec_yaml

URL, BOARD, CHANNEL = ("https://your-vllm.example.invalid/v1", "https://msgboard.example.invalid",
                       "your-run3-channel")
ROUTER = "deepseek-ai/DeepSeek-V4.1-Flash-1017:novita"  # as in chatbot-v2 (router /v1/models)
ROUTER_URL, ROUTER_PRICE = "https://router.huggingface.co/v1", [0.30, 1.20, 0.30]  # USD per 1M
FILES = {"selfhosted": "spec.local.yaml", "smoke": "spec.smoke.yaml",
         "standin": "spec.standin.yaml", "jobs": "spec.jobs.yaml",
         "router-smoke": "spec.router-smoke.yaml"}
HEAD = ("# GENERATED by render.py --variant {v} from spec.yaml (+ waves.yaml for the worker\n"
        "# slots). Do not edit: change spec.yaml or the environment and render again.\n")


def env(name: str, default: str) -> str:
    return os.environ.get(name) or default


def render(variant: str = "selfhosted", placeholders: bool = False) -> dict:
    e = (lambda n, d: d) if placeholders else env
    d = load_spec_yaml((HERE / "spec.yaml").read_text())
    standin = variant == "standin"
    worker = e("MODEL_WORKER", ROUTER if standin else "MODEL_WORKER")
    ids = {"MODEL_WORKER": worker, "MODEL_INTERVIEWER": e("MODEL_INTERVIEWER", worker)}
    for m in d["models"].values():
        prov, _, mid = m["model"].partition(":")
        m["model"] = f"{prov}:{ids.get(mid, mid)}"
    d["providers"]["vllm"]["base_url"] = e("OPENAI_BASE_URL", ROUTER_URL if standin else URL)
    d["comms"].update(url=e("CHATBOT_BOARD_URL", BOARD), channel=e("CHATBOT_CHANNEL", CHANNEL))
    if run := e("CHATBOT_RUN", ""):
        d["swarm"] = f"run3-{run}"
    sched = load(HERE / "waves.yaml")
    loops = [t for t in d["types"].values() if t.get("loop")]
    if variant == "jobs":
        apw = d["types"]["agent"]["agents_per_worker"]
        d.update(compute="hf-jobs", namespace=e("RUN3_NAMESPACE", "your-namespace"),
                 bucket=e("RUN3_BUCKET", "hf://buckets/your-namespace/your-bucket"))
        d["world"] = {"url": e("RUN3_WORLD_URL", "https://your-world-space.hf.space"),
                      "token_env": "CHATBOT_WORLD_TOKEN"}
        live = sched.cap * d["spawn"]["agent"]["max"]  # one live interviewer per agent at most
        d["types"]["interviewer"]["workers"] = {"initial": 0, "max_extra": math.ceil(live / apw)}
        d["types"]["interviewer"]["secrets"] = ["OPENAI_API_KEY"]
        for t in loops:
            t["secrets"] = ["OPENAI_API_KEY"]
    elif variant == "router-smoke":
        d["providers"] = {"hf": {"type": "openai_compat", "base_url": "https://router.huggingface.co/v1",
                                 "api_key_env": "HF_TOKEN", "timeout_s": 180, "max_retries": 5,
                                 "pricing": {ROUTER: ROUTER_PRICE}}}
        for m in d["models"].values():
            m["model"] = f"hf:{ROUTER}"
        for t in loops:
            t["max_budget_usd"] = 0.33  # per prompt: chatbot-v2's $0.20 for 12 calls, at 20
            t["loop"] = {**t["loop"], "while": {"until": "20m", "max_rounds": 200,
                                                "agent_usd": 2.50},
                         "final": {**t["loop"]["final"], "reserve_usd": 0.30}}
        d["types"]["interviewer"]["max_budget_usd"] = 0.15
        d["limits"]["budget_usd"] = 15
    elif standin:  # the router as the endpoint: its key, its prices, $ caps, a slower cadence
        prov = d["providers"]["vllm"]
        prov.update(api_key_env="HF_TOKEN", self_hosted=False, timeout_s=180,
                    pricing={ids["MODEL_WORKER"]: ROUTER_PRICE,
                             ids["MODEL_INTERVIEWER"]: ROUTER_PRICE})
        for t in loops:
            t["max_budget_usd"] = 0.33  # per prompt: chatbot-v2's $0.20 for 12 calls, at 20
            t["loop"] = {**t["loop"], "every": "60s",
                         "while": {"until": "20m", "max_rounds": 40, "agent_usd": 3.00},
                         "final": {**t["loop"]["final"], "reserve_usd": 0.30}}
        d["types"]["interviewer"]["max_budget_usd"] = 0.15  # per interviewer, as chatbot-v2
        d["limits"].update(budget_usd=30, spawned_total=64)
    elif variant == "smoke":
        for t in loops:  # a hard 30-min loop and a per-agent round cap; no $ caps
            t["loop"] = {**t["loop"], "while": {"until": "30m", "max_rounds": 120}}
    elif variant != "selfhosted":
        raise SystemExit(f"unknown variant {variant!r}")
    return d


def write(variant: str, out: Path, placeholders: bool = False) -> Path:
    out.write_text(HEAD.format(v=variant) + yaml.safe_dump(render(variant, placeholders),
                                                           sort_keys=False, width=100))
    return out


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--variant", default="selfhosted", choices=list(FILES))
    ap.add_argument("--out", type=Path)
    ap.add_argument("--committed", action="store_true",
                    help="write the committed generated spec (placeholders only)")
    a = ap.parse_args()
    if a.committed:
        print(write(a.variant, HERE / FILES[a.variant], placeholders=True))
        return
    out = a.out or HERE / FILES[a.variant].replace(".yaml", ".local.yaml").replace(
        ".local.local", ".local")
    print(write(a.variant, out))


if __name__ == "__main__":
    main()
